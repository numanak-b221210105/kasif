def tr_lower(s: str) -> str:
    """Türkçe kurallarıyla küçük harf: I → ı, İ → i."""
    return unicodedata.normalize("NFC", s.replace("I", "ı").replace("İ", "i")).lower()


def tokens(s: str) -> list[str]:
    return _WORD.findall(tr_lower(s))


def ascii_fold(s: str) -> str:
    """Tablo ve sütun adları için: 'Sipariş Tarihi' → 'siparis_tarihi'."""
    table = str.maketrans("çğıöşüâîûÇĞİÖŞÜ", "cgiosuaiucgiosu")
    s = tr_lower(s).translate(table)
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s or "kolon"


def tok_match(q: str, s: str) -> bool:
    """Sorudaki sözcük `q`, eşanlamlıdaki sözcük `s` ile (ek toleransıyla) eşleşiyor mu?"""
    if q == s:
        return True
    if not q.startswith(s):
        return False
    rest = q[len(s) :]
    if rest in SUFFIXES:
        return True
    # uzun köklerde serbest ek: "satışlarımızın", "müşterilerimize"
    return len(s) >= 5 and len(rest) <= 6


def local_today():
    """Bilgisayarın yerel saat dilimine göre bugünün tarihi."""
    from datetime import datetime

    return datetime.now().astimezone().date()
